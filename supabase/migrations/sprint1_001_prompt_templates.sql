-- Sprint 1: Prompt Templates
CREATE TABLE IF NOT EXISTS prompt_templates (
  id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at       TIMESTAMPTZ DEFAULT now(),
  name             TEXT NOT NULL,
  tone_description TEXT NOT NULL,
  system_prompt    TEXT NOT NULL,
  content_types    TEXT[] DEFAULT ARRAY['article','post','concept'],
  is_default       BOOLEAN DEFAULT false,
  is_active        BOOLEAN DEFAULT true,
  usage_count      INTEGER DEFAULT 0,
  version          TEXT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_single_default
  ON prompt_templates (is_default)
  WHERE is_default = true;

CREATE INDEX IF NOT EXISTS idx_templates_active
  ON prompt_templates (is_active);

-- RLS
ALTER TABLE prompt_templates ENABLE ROW LEVEL SECURITY;
CREATE POLICY "allow_all_templates" ON prompt_templates
  FOR ALL USING (true) WITH CHECK (true);

