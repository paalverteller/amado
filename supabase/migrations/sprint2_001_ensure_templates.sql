-- Создание таблицы шаблонов промптов
CREATE TABLE IF NOT EXISTS prompt_templates (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at TIMESTAMPTZ DEFAULT now(),
  name TEXT UNIQUE NOT NULL,
  tone_description TEXT,
  system_prompt TEXT NOT NULL,
  content_types TEXT[] DEFAULT '{}',
  is_default BOOLEAN DEFAULT false,
  is_active BOOLEAN DEFAULT true,
  usage_count INTEGER DEFAULT 0,
  version TEXT DEFAULT '1.0.0'
);

-- Настройка политик безопасности RLS
ALTER TABLE prompt_templates ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "allow_all_prompt_templates" ON prompt_templates;
CREATE POLICY "allow_all_prompt_templates" ON prompt_templates FOR ALL USING (true) WITH CHECK (true);

-- Индексы для быстрого поиска
CREATE INDEX IF NOT EXISTS idx_prompt_templates_is_active ON prompt_templates(is_active);
CREATE INDEX IF NOT EXISTS idx_prompt_templates_is_default ON prompt_templates(is_default);

